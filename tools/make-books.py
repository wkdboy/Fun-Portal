"""Builds apps/stories/books/ and apps/stories/books.js from unzipped Book Dash "ebook" downloads (CC BY 4.0).
Usage: python tools/make-books.py <folder holding one unzipped folder per book>
Each book: cover (the first image, a single square page) plus story spreads (images 5-16), resized to 1400px wide JPEGs."""
import glob, json, os, re, sys
from PIL import Image

SRC = sys.argv[1]
OUT = os.path.join(os.path.dirname(__file__), '..', 'apps', 'stories')
FIRST, LAST = 4, 15  # 0-based positions of the first and last story spreads (after cover, "belongs to", pattern, licence)

# slug: (title, [(role, name)], year published)
BOOKS = {
    'come-back-cat': ('Come back, cat!', [('Written by', 'Nicola Rijsdijk'), ('Illustrated by', 'Karen Lilje'), ('Designed by', 'Sam Scarborough')], 2014),
    'clever-pig': ('Clever Pig', [('Written by', 'Nathalie Koenig'), ('Illustrated by', 'Joshua Morgan'), ('Designed by', 'Lee-Ann Knowles'), ('Edited by', 'Carol Kagezi')], 2016),
    'little-goat': ('Little Goat', [('Written by', 'Mirna Lawrence'), ('Illustrated by', 'Nicola Anne Smith'), ('Designed by', 'Tiffany Mac Sherry'), ('Edited by', 'Nabeela Kalla')], 2016),
    'how-do-you-sleep': ('How do you sleep?', [('Written and edited by', 'Diane Awerbuck'), ('Illustrated by', 'Alex Latimer'), ('Designed by', 'Georgia Demertzis')], 2022),
    'lions-are-always-brave': ('Lions Are Always Brave', [('Written by', 'Daniel Browde'), ('Illustrated by', 'Carlos Amato'), ('Designed by', 'Thabang Tlhako'), ('Edited by', 'Alison Ziki')], 2018),
    'sleepy-mr-sloth': ('Sleepy Mr Sloth', [('Written by', 'Paul Kennedy'), ('Illustrated by', 'Graham Paterson'), ('Designed by', 'Nick Mulgrew'), ('Edited by', 'Arthur Attwell and Tarryn-Anne Anderson')], 2014),
    'small-birds-big-adventure': ("Small Bird's Big Adventure", [('Written by', 'Nick Mulgrew'), ('Illustrated by', 'Wesley van Eeden'), ('Designed by', 'Jennifer Jacobs'), ('Edited by', 'Bongani Kona')], 2016),
    'monkey-business': ('Monkey business', [('Written by', 'Magriet Kruger'), ('Illustrated by', 'Brice Reignier'), ('Designed by', 'Wilna Combrinck'), ('Edited by', 'Katie Huston')], 2023),
    'amazing-daisy': ('Amazing Daisy!', [('Written by', 'Nozizwe Herero'), ('Illustrated by', 'Siya Masuku'), ('Designed by', 'Leona Ingram'), ('Edited by', 'Ester Levinson and Melissa Davidson')], 2015),
}

def order(p):
    b = os.path.basename(p)
    return -1 if 'cover' in b else int(re.findall(r'(\d+)\.jpg$', b)[0])

def save(im, path, width, q=80):
    im = im.convert('RGB')
    if im.width > width:
        im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    im.save(path, 'JPEG', quality=q, optimize=True, progressive=True)

shelf = []
for slug, (title, credits, year) in BOOKS.items():
    files = sorted(glob.glob(os.path.join(SRC, slug, '*', 'images', '*.jpg')), key=order)
    out = os.path.join(OUT, 'books', slug)
    os.makedirs(out, exist_ok=True)
    cover = Image.open(files[0])
    save(cover, os.path.join(out, 'cover.jpg'), 600)
    n = 0
    for f in files[FIRST:LAST + 1]:
        n += 1
        save(Image.open(f), os.path.join(out, f'{n:02d}.jpg'), 1400)
    size = sum(os.path.getsize(p) for p in glob.glob(os.path.join(out, '*.jpg')))
    print(f'{slug}: {n} pages, {size / 1e6:.1f} MB')
    shelf.append({'id': slug, 'title': title, 'pages': n, 'credits': credits, 'year': year, 'url': f'https://bookdash.org/books/{slug}/'})

with open(os.path.join(OUT, 'books.js'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/make-books.py. Book Dash stories, CC BY 4.0. Each folder in books/ has cover.jpg and 01.jpg...\n')
    f.write('export const BOOKS = ' + json.dumps(shelf, indent=2, ensure_ascii=False) + ';\n')
